"""Run synthetic media tests and annotate bounded assertions, never upload logs."""

import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path


def escape(value):
    return value.replace("%", "%25").replace("\r", "%0D").replace("\n", "%0A")


with tempfile.TemporaryDirectory() as folder:
    report = Path(folder) / "media.xml"
    result = subprocess.run(  # noqa: S603 - fixed test command
        [sys.executable, "-m", "pytest", "tests/studio/test_media_studio.py", "-q", "--junitxml=" + str(report)],
        check=False,
    )  # noqa: S603 - fixed test command
    if result.returncode and report.is_file():
        root = ET.parse(report).getroot()  # noqa: S314 - report generated by our own tests
        for case in root.iter("testcase"):
            for tag in ("failure", "error"):
                for failure in case.findall(tag):
                    print(
                        "::error title="
                        + escape(case.get("name", "Media test"))
                        + "::"
                        + escape(failure.get("message", "Failed")[:1600])
                    )
    raise SystemExit(result.returncode)
