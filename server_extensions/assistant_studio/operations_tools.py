"""Expose existing grants to chat; never expose permission-creation tools."""

import functools
import sys
import uuid

from fastapi import HTTPException
from sqlalchemy import select

from . import operations_service as service
from .operations_models import OperationGrant, OperationJob

_DHANZ_OPERATIONS_CHAT_VERSION = 3


def install_prompt_guidance():
    # Patch only the already loaded chat module, preserving the private prompt implementation.
    chat = sys.modules.get("app.services.chat_service")
    original = getattr(chat, "build_system_prompt", None)
    if original is None or getattr(original, "_dhanz_connected_guidance", False):
        return

    @functools.wraps(original)
    def prompt(*args, **kwargs):
        result = original(*args, **kwargs)
        available = (kwargs.get("capabilities") or {}).get("available_tools_this_reply", [])
        if kwargs.get("tools") and "github_workspace" in available:
            result += (
                "\nConnected GitHub/server workflows are available in this reply. Check github_workspace "
                "or connected_operations before making capability claims. Use the user's actual connected "
                "repositories and standing permissions for requested tasks; do not invent a security/privacy "
                "prohibition or say the user must do every action manually. github_workspace can read selected "
                "repositories and start coding drafts. Publication uses an existing repository/branch grant "
                "or the coding workspace's explicit review. Server execution uses only paired named recipes "
                "with existing grants. Do not expand permissions, merge, or claim arbitrary terminal access. "
                "If the task is unclear, ask for the actual change and repository, not credentials. Internal "
                "request keys are generated by the server. Queued work is not complete: inspect tool status "
                "and never promise an automatic follow-up chat message. A codex_connected flag reports prior "
                "verified Codex generation, not whether GitHub tools are connected."
            )
        return result

    prompt._dhanz_connected_guidance = True
    chat.build_system_prompt = prompt


def request_key(ctx, grant_id):
    """One execution per grant per assistant reply, independent of model arguments.

    The persisted reply ID survives context reconstruction. Older contexts without
    that field share a random key on the same context object for the reply.
    """
    reply = getattr(ctx, "assistant_message_id", None)
    if reply is not None:
        identity = f"dhanz-operation:{ctx.user_id}:{ctx.conversation_id}:{reply}:{grant_id}"
        return "chat_" + uuid.uuid5(uuid.NAMESPACE_URL, identity).hex
    keys = getattr(ctx, "_dhanz_operation_keys", None)
    if keys is None:
        keys = {}
        ctx._dhanz_operation_keys = keys
    identity = (str(ctx.user_id), str(ctx.conversation_id), str(grant_id))
    return keys.setdefault(identity, "chat_" + uuid.uuid4().hex)


def install_tools():
    from app.services import assistant_tools as tools
    from dhanz_ai import ToolSpec

    install_prompt_guidance()

    async def catalog(ctx, args):
        async with ctx.maker() as db:
            grants = list(await db.scalars(select(OperationGrant).where(OperationGrant.user_id == ctx.user_id)))
            jobs = list(
                await db.scalars(
                    select(OperationJob)
                    .where(OperationJob.user_id == ctx.user_id)
                    .order_by(OperationJob.created_at.desc())
                    .limit(10)
                )
            )
            return tools.ToolOutcome(
                {
                    "permissions": [service.public(g) for g in grants if service.active(g)],
                    "recent_tasks": [service.public(j) for j in jobs],
                },
                "Checked connected operations",
            )

    async def run(ctx, args):
        try:
            identifier = uuid.UUID(str(args.get("grant_id", "")))
            key = request_key(ctx, identifier)
            async with ctx.maker() as db:
                row = await service.enqueue(db, ctx.user_id, identifier, key)
                return tools.ToolOutcome(service.public(row), "Queued authorized server task")
        except (HTTPException, ValueError) as exc:
            raise tools.ToolInputError(str(exc.detail) if isinstance(exc, HTTPException) else str(exc)) from None

    tools.TOOLS["connected_operations"] = tools.Tool(
        ToolSpec(
            "connected_operations",
            "List this user's standing permissions and actual server task results. "
            "For AWS/server health, restart or approved deployment requests, check these connections before "
            "asking for instance IDs or AWS CLI details. "
            "Never claim a queued task completed. Permissions are configured by the user in Connected operations.",
            {"type": "object", "properties": {}, "additionalProperties": False},
        ),
        "Checking connected operations",
        catalog,
    )
    tools.TOOLS["run_connected_task"] = tools.Tool(
        ToolSpec(
            "run_connected_task",
            "Run a named server recipe under an existing user-approved standing permission. "
            "First list connected_operations. Choose only a matching active server_task grant for the user's task. "
            "No extra approval is needed within that grant. The server generates internal request keys; "
            "never ask the user for one. Repeated calls for this grant in the same reply return the same task. "
            "If an outcome is uncertain, inspect connected_operations; do not start another reply to retry it. "
            "No arbitrary commands or arguments are accepted.",
            {
                "type": "object",
                "properties": {"grant_id": {"type": "string"}},
                "required": ["grant_id"],
                "additionalProperties": False,
            },
        ),
        "Running authorized server task",
        run,
    )

    async def workspace(ctx, args):
        from pydantic import ValidationError
        from sqlalchemy.exc import IntegrityError

        from app.core import rate_limit
        from app.models import User
        from app.services import github_service as gh

        from . import builder
        from . import coding_service as coding
        from .coding_models import CodingDraft
        from .coding_routes import DraftInput

        try:
            if ctx.settings is None:
                raise ValueError("GitHub workspace settings are unavailable in this reply.")
            operation = args.get("operation")
            async with ctx.maker() as db:
                user = await db.get(User, ctx.user_id)
                if user is None or not user.is_active:
                    raise ValueError("Sign in with an active account.")
                if operation == "repositories":
                    data = await gh.read(db, ctx.settings, user.id, "repositories")
                elif operation in {"file", "directory"}:
                    data = await gh.read(
                        db,
                        ctx.settings,
                        user.id,
                        operation,
                        args.get("repository", ""),
                        args.get("path", ""),
                        args.get("branch", ""),
                    )
                elif operation == "models":
                    data = {"models": [] if user.routing_policy == "local_only" else await builder.models(ctx.settings)}
                elif operation == "status":
                    row = await coding.owned(db, user.id, uuid.UUID(str(args.get("draft_id", ""))))
                    data = await coding.public(db, row)
                    data["workspace"] = "/coding"
                elif operation == "start":
                    if user.routing_policy == "local_only":
                        raise ValueError("External coding generation is disabled in local-only mode.")
                    repository = gh.repository_name(args.get("repository", ""))
                    key = request_key(ctx, "github-start:" + repository)
                    row = await db.scalar(
                        select(CodingDraft).where(CodingDraft.user_id == user.id, CodingDraft.request_key == key)
                    )
                    if row is None:
                        await rate_limit.enforce("coding:" + str(user.id), 5)
                        models = await builder.models(ctx.settings)
                        if not models:
                            raise ValueError("No coding API model is available for this account's configured provider.")
                        model = args.get("model") or next((m for m in models if "codex" in m.lower()), models[0])
                        instructions = args.get("instructions") or ""
                        body = DraftInput(
                            title=args.get("title") or instructions[:100],
                            instructions=instructions,
                            model=model,
                            request_key=key,
                            repository=repository,
                            base_branch=args.get("branch", ""),
                            paths=args.get("paths", []),
                            runtime=args.get("runtime", "web"),
                            workdir=args.get("workdir", ""),
                            kind=args.get("kind", "app"),
                            auto_repair=False,
                        )
                        try:
                            row = await coding.queue_draft(db, ctx.settings, user, body)
                        except IntegrityError:
                            await db.rollback()
                            row = await db.scalar(
                                select(CodingDraft).where(
                                    CodingDraft.user_id == user.id, CodingDraft.request_key == key
                                )
                            )
                            if row is None:
                                raise ValueError(
                                    "Coding request changed concurrently. Check the workspace before retrying."
                                ) from None
                    data = await coding.public(db, row)
                    data["workspace"] = "/coding"
                    data["next_step"] = (
                        "Generation is queued/running, not a finished repository change. Check status. "
                        "An applicable standing publication grant can publish a new branch and draft PR after "
                        "generation/validation; otherwise review and publish in Chat with Codex. No merge or "
                        "deployment."
                    )
                else:
                    raise ValueError("Choose repositories, directory, file, models, start or status.")
                return tools.ToolOutcome(
                    data, "Checked GitHub workspace" if operation != "start" else "Queued coding draft"
                )
        except (gh.GitHubError, builder.BuildError, HTTPException, ValidationError, ValueError) as exc:
            if isinstance(exc, HTTPException):
                detail = str(exc.detail)
            elif isinstance(exc, ValidationError):
                detail = (
                    "Provide a change request of 5–12000 characters, a selected repository and valid workspace options."
                )
            elif isinstance(exc, builder.BuildError):
                detail = builder.failure_message(exc)
            else:
                detail = str(exc)
            raise tools.ToolInputError(detail) from None

    properties = {
        name: {"type": "string"}
        for name in ("repository", "path", "branch", "instructions", "title", "model", "draft_id", "workdir")
    }
    properties.update(
        {
            "operation": {"type": "string", "enum": ["repositories", "directory", "file", "models", "start", "status"]},
            "runtime": {"type": "string", "enum": ["python", "web", "flutter"]},
            "kind": {"type": "string", "enum": ["app", "agent"]},
            "paths": {"type": "array", "items": {"type": "string"}, "maxItems": 12},
        }
    )
    tools.TOOLS["github_workspace"] = tools.Tool(
        ToolSpec(
            "github_workspace",
            "Use this authorized workflow for requested GitHub coding work instead of claiming no repository access. "
            "repositories lists this account's selected repositories; directory/file reads source "
            "(path, branch optional). "
            "start prepares changes using the existing coding workspace: supply exact repository, "
            "requested instructions, "
            "runtime and up to 12 relevant source paths discovered with directory/file. Configured "
            "OpenAI API usage applies. "
            "model is optional; an actually listed Codex model is preferred. Never put secrets in instructions. "
            "The server generates request keys and deduplicates starts per repository/reply. status requires draft_id. "
            "Check actual results: only standing repository grants permit automatic draft PR publication; otherwise "
            "the user reviews/publishes in Chat with Codex. No merge, arbitrary server commands or "
            "automatic chat follow-up.",
            {"type": "object", "properties": properties, "required": ["operation"], "additionalProperties": False},
        ),
        "Working with GitHub",
        workspace,
    )
